#!/usr/bin/env python3
"""
Generate ROS2 .msg files (and ament packages) from DDS IDL files.

All output goes under a single workspace dir (default: ./work) which
should be gitignored. One ament package is generated per IDL module
whose name is a valid ROS 2 package name (lowercase letters / digits
/ underscores, starting with a letter), at:

    <work>/<module>/{package.xml,CMakeLists.txt,msg/<Struct>.msg}

Cross-package refs are emitted as '<owner_module>/<Type>' so the
resulting DDS type '<module>::msg::dds_::<Type>_' matches what bare
DDS apps register on the wire — closes the rosbridge ↔ bare-DDS
interop gap.

Structs in IDL files whose `module` name is not a valid ROS pkg name
(CamelCase, missing module declaration, etc.) are SKIPPED — they will
not appear in any ROS package. Fix the IDL to give them a proper
lowercase module to include them.

After generation, run colcon from <work> to build all packages at
once. See docker/Dockerfile.ros for the production invocation.

Invocation paths
----------------
  • Host C++ build (automatic): idl/rosbridge/CMakeLists.txt runs this
    script via execute_process at CMake configure time, so any
    `cmake ..` on the host project regenerates work/ in lockstep with
    IDL changes. CONFIGURE_DEPENDS on idl/dds/**/*.idl makes CMake
    re-run when IDL changes.

  • Container image build: docker/Dockerfile.ros calls the script
    directly (CMake isn't involved) and then `cd work && colcon build`.

  • Manual / dev: run from the rosbridge dir.

Usage:
    cd idl/rosbridge && python3 idl_to_msg.py --idl-root ../dds
    # generates everything under ./work/
"""

import argparse
import re
import shutil
import sys
from pathlib import Path
from typing import Callable, Dict, List, Optional, Tuple


# Marker placed in every auto-generated package.xml. Used to recognise our
# own previously-emitted package dirs so we can safely remove stale ones
# (e.g. when an IDL module is renamed or removed).
GEN_MARKER = "AUTO-GENERATED by idl/rosbridge/idl_to_msg.py"


# ── Type mapping: DDS IDL → ROS2 .msg ──────────────────────────────────────
TYPE_MAP = {
    "long long":  "int64",
    "long":       "int32",
    "int32":      "int32",
    "int64":      "int64",
    "short":      "int16",
    "octet":      "uint8",
    "boolean":    "bool",
    "float":      "float32",
    "double":     "float64",
    "string":     "string",
}

# sequence<X> → X[]
SEQUENCE_RE = re.compile(r"sequence\s*<\s*([^>]+?)\s*>")

# Known enum types defined in DDS IDL → mapped to int32 in .msg
KNOWN_ENUMS = {
    "ReturnValue", "CommonStatusType",
    "DiagnosticStatusType",
    "ServiceType", "RecoveryPolicy", "ReturnCode",
    "ServiceMode", "ServiceState", "OsType",
    # F013: container enums added to LifecycleCommon.idl
    "ContainerType", "ContainerState",
}

# Rename DDS struct names → ROS2 .msg names
STRUCT_RENAME = {
    "Service": "LifecycleService",
}

# Struct names to skip entirely (placeholder/dummy types not used in messaging)
SKIP_STRUCTS = {
    "DummyType2", "DummyTypeT", "DiagnosticCommonDummy",
    "ReturnValueStruct",
}

# IDL files to skip outright (covered elsewhere or irrelevant)
SKIP_FILES = {
    "String_.idl", "Gid.idl", "NodeEntitiesInfo.idl", "ParticipantEntitiesInfo.idl",
}

# Valid ROS 2 package name: starts with a-z, then a-z / 0-9 / _
VALID_PKG_RE = re.compile(r"^[a-z][a-z0-9_]*$")


def is_valid_ros_pkg(name: str) -> bool:
    return bool(name) and bool(VALID_PKG_RE.match(name))


def map_type(dds_type: str, resolver: Callable[[str], Optional[str]]) -> str:
    """Convert a DDS IDL type to ROS2 .msg type using a resolver for nested
    custom types. resolver(struct_name) returns the owner package name or
    None if the name is not a known custom struct.
    """
    dds_type = dds_type.strip()

    m = SEQUENCE_RE.match(dds_type)
    if m:
        return map_type(m.group(1), resolver) + "[]"

    if dds_type in KNOWN_ENUMS:
        return "int32"

    for dds, ros in TYPE_MAP.items():
        if dds_type == dds:
            return ros

    renamed = STRUCT_RENAME.get(dds_type, dds_type)
    owner = resolver(renamed)
    if owner is not None:
        return f"{owner}/{renamed}"

    print(f"  [WARN] Unknown type: '{dds_type}' → kept as-is", file=sys.stderr)
    return dds_type


def parse_idl_file(idl_path: Path) -> Tuple[str, List[Tuple[str, str, Path]]]:
    """Return (module_name, [(ros_struct_name, body_raw, idl_path), ...])."""
    text = idl_path.read_text()
    text = re.sub(r"//[^\n]*", "", text)
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    text = re.sub(r"#include\s+[^\n]+", "", text)

    module_m = re.search(r"module\s+(\w+)", text)
    module_name = module_m.group(1) if module_m else ""

    structs: List[Tuple[str, str, Path]] = []
    for m in re.finditer(r"struct\s+(\w+)\s*\{([^}]*)\}", text, re.DOTALL):
        sname = m.group(1)
        body = m.group(2)
        if sname in SKIP_STRUCTS:
            continue
        ros_name = STRUCT_RENAME.get(sname, sname)
        structs.append((ros_name, body, idl_path))

    return module_name, structs


def parse_fields(body: str, resolver: Callable[[str], Optional[str]]) \
        -> List[Tuple[str, str]]:
    """Parse struct body into [(ros_type, field_name), ...]."""
    body = body.strip()
    if not body:
        return []
    fields: List[Tuple[str, str]] = []
    for line in body.splitlines():
        line = line.strip().rstrip(";").strip()
        if not line:
            continue
        line = re.sub(r"@key\s+", "", line)
        parts = line.rsplit(None, 1)
        if len(parts) == 2:
            dds_type, field_name = parts
            fields.append((map_type(dds_type.strip(), resolver), field_name))
    return fields


def render_msg(struct_name: str, fields: List[Tuple[str, str]],
               module_label: str, idl_path: Path, idl_root: Path) -> str:
    rel = idl_path.relative_to(idl_root.parent)
    lines = [
        f"# Auto-generated from idl/{rel.as_posix()}",
        f"# Module: {module_label}, Struct: {struct_name}",
    ]
    if not fields:
        lines.append("# Empty message")
    else:
        for ros_type, field_name in fields:
            lines.append(f"{ros_type} {field_name}")
    return "\n".join(lines) + "\n"


def write_if_changed(path: Path, content: str) -> bool:
    if path.exists() and path.read_text() == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    return True


# ── Per-module package templates ───────────────────────────────────────────

PACKAGE_XML_TMPL = """<?xml version="1.0"?>
<?xml-model href="http://download.ros.org/schema/package_format3.xsd" schematypens="http://www.w3.org/2001/XMLSchema"?>
<!-- AUTO-GENERATED by idl/rosbridge/idl_to_msg.py — DO NOT EDIT -->
<package format="3">
  <name>{pkg}</name>
  <version>0.1.0</version>
  <description>{description}</description>
  <maintainer email="dev@obigo.com">MMF Team</maintainer>
  <license>Proprietary</license>

  <buildtool_depend>ament_cmake</buildtool_depend>
  <buildtool_depend>rosidl_default_generators</buildtool_depend>

  <exec_depend>rosidl_default_runtime</exec_depend>
{deps}
  <member_of_group>rosidl_interface_packages</member_of_group>

  <export>
    <build_type>ament_cmake</build_type>
  </export>
</package>
"""

CMAKELISTS_TMPL = """cmake_minimum_required(VERSION 3.8)
project({pkg})

# AUTO-GENERATED by idl/rosbridge/idl_to_msg.py — DO NOT EDIT.
# Regenerate by running idl_to_msg.py from idl/rosbridge/.

find_package(ament_cmake REQUIRED)
find_package(rosidl_default_generators REQUIRED){find_deps}

file(GLOB MSG_FILES CONFIGURE_DEPENDS "${{CMAKE_CURRENT_SOURCE_DIR}}/msg/*.msg")
set(MSG_FILES_RELATIVE)
foreach(f ${{MSG_FILES}})
  file(RELATIVE_PATH rel "${{CMAKE_CURRENT_SOURCE_DIR}}" "${{f}}")
  list(APPEND MSG_FILES_RELATIVE "${{rel}}")
endforeach()

if(NOT MSG_FILES_RELATIVE)
  message(FATAL_ERROR "[{pkg}] no .msg files found")
endif()

rosidl_generate_interfaces(${{PROJECT_NAME}}
  ${{MSG_FILES_RELATIVE}}{deps_arg}
)

ament_export_dependencies(rosidl_default_runtime)
ament_package()
"""


def write_pkg_files(pkg_dir: Path, pkg_name: str, dep_pkgs: List[str],
                    description: str) -> None:
    deps_xml = "\n".join(f"  <depend>{d}</depend>" for d in dep_pkgs)
    if deps_xml:
        deps_xml += "\n"
    find_deps = "".join(f"\nfind_package({d} REQUIRED)" for d in dep_pkgs)
    deps_arg = ""
    if dep_pkgs:
        deps_arg = "\n  DEPENDENCIES " + " ".join(dep_pkgs)

    pkg_dir.mkdir(parents=True, exist_ok=True)
    write_if_changed(
        pkg_dir / "package.xml",
        PACKAGE_XML_TMPL.format(pkg=pkg_name, deps=deps_xml, description=description),
    )
    write_if_changed(
        pkg_dir / "CMakeLists.txt",
        CMAKELISTS_TMPL.format(pkg=pkg_name, find_deps=find_deps, deps_arg=deps_arg),
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--idl-root", required=True,
                        help="Root directory of DDS IDL files (e.g. ../dds)")
    parser.add_argument("--work-dir", default="./work",
                        help="Workspace dir for all generated packages. "
                             "Each package lives at <work-dir>/<pkg>/. "
                             "Default: ./work")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    idl_root = Path(args.idl_root).resolve()
    work_dir = Path(args.work_dir).resolve()

    idl_files = sorted(f for f in idl_root.rglob("*.idl") if f.name not in SKIP_FILES)

    # ── Cleanup stale auto-generated dirs ──────────────────────────────────
    # Any subdir of work/ whose package.xml carries our AUTO-GENERATED marker
    # is owned by this script. If it does not correspond to a current valid
    # IDL module we delete it (handles module renames + the removal of the
    # old flat 'mmf_interfaces' package). User-placed dirs without the
    # marker are left alone.
    if not args.dry_run and work_dir.is_dir():
        # Compute current valid modules first (cheap pre-pass).
        current_modules = set()
        for idl_path in idl_files:
            module, _ = parse_idl_file(idl_path)
            if is_valid_ros_pkg(module):
                current_modules.add(module)

        for child in work_dir.iterdir():
            if not child.is_dir():
                continue
            pkg_xml = child / "package.xml"
            if pkg_xml.is_file() and GEN_MARKER in pkg_xml.read_text():
                if child.name not in current_modules:
                    print(f"  [clean] removing stale {child.name}/")
                    shutil.rmtree(child)

    # ── Phase 1: parse all IDLs and build owner map ────────────────────────
    type_owner: Dict[str, str] = {}                # struct → owner pkg
    valid_modules: Dict[str, List[Tuple[str, str, Path]]] = {}
    skipped: List[Tuple[str, str, Path]] = []      # (module, struct, path)

    for idl_path in idl_files:
        module, structs = parse_idl_file(idl_path)
        for sname, body, p in structs:
            if is_valid_ros_pkg(module):
                type_owner[sname] = module
                valid_modules.setdefault(module, []).append((sname, body, p))
            else:
                skipped.append((module or "(none)", sname, p))

    if skipped:
        print("[WARN] structs skipped (module name is not a valid ROS pkg):",
              file=sys.stderr)
        for module, sname, p in skipped:
            print(f"  - {sname} (module='{module}', from {p.name})",
                  file=sys.stderr)

    # ── Phase 2: emit per-module packages ──────────────────────────────────
    resolver: Callable[[str], Optional[str]] = lambda name: type_owner.get(name)

    pkg_changed = 0
    for module, items in sorted(valid_modules.items()):
        pkg_dir = work_dir / module
        msg_dir = pkg_dir / "msg"
        # Determine cross-package deps for this module
        cross_deps: set = set()
        for sname, body, idl_path in items:
            fields = parse_fields(body, resolver)
            for ros_type, _ in fields:
                # extract base type (strip [] sequence suffix)
                base = ros_type.rstrip("[]")
                if "/" in base:
                    pkg = base.split("/", 1)[0]
                    if pkg != module:
                        cross_deps.add(pkg)
            content = render_msg(sname, fields, module, idl_path, idl_root)
            if args.dry_run:
                print(f"  [{module}-dry] {sname}.msg")
            elif write_if_changed(msg_dir / f"{sname}.msg", content):
                pkg_changed += 1
                print(f"  [{module}] {sname}.msg")

        if not args.dry_run:
            write_pkg_files(
                pkg_dir, module, sorted(cross_deps),
                description=f"Auto-generated DDS interface messages for "
                            f"module '{module}'.",
            )

    print(f"\nPackages generated: {len(valid_modules)} "
          f"({', '.join(sorted(valid_modules)) or 'none'})")
    if skipped:
        print(f"Structs skipped:    {len(skipped)} (see warnings above)")
    print(f"Output workspace:   {work_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
