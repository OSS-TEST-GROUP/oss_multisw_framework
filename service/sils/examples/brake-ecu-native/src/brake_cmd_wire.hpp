#ifndef BRAKE_ECU_NATIVE_WIRE_HPP
#define BRAKE_ECU_NATIVE_WIRE_HPP

// BrakeCmdWireCodec -- a developer-authored IWireCodec over a NATIVE custom DDS type
// (libsils_vecu example, P4b). This is the point of the wire port: the vECU publishes
// its own contract type (BrakeCmd, typed fields) instead of the built-in VISS envelope,
// with NO change to RunProbe -- it is injected exactly like the built-in codecs:
//
//     RunProbe(cfg, behavior, plant, std::make_unique<BrakeCmdWireCodec>());
//
// The behavior stays wire-agnostic: RunProbe hands the codec each tick's BehaviorOutput,
// and the codec maps out.value -> BrakeCmd.force (the JSON request_json is unused on this
// wire). So the SAME BrakeBehavior drives either the VISS-envelope ECU or this native one.

#include <cmath>
#include <string>
#include <vector>

#include <fastdds/dds/domain/DomainParticipant.hpp>
#include <fastdds/dds/publisher/DataWriter.hpp>
#include <fastdds/dds/subscriber/DataReader.hpp>
#include <fastdds/dds/subscriber/SampleInfo.hpp>
#include <fastdds/dds/topic/TypeSupport.hpp>

#include "BrakeCmdPubSubTypes.hpp"  // generated by this example's CMake (fastddsgen)
#include "wire.hpp"                 // sils::IWireCodec / WireFault / WireInbound (from sils_vecu)

class BrakeCmdWireCodec : public sils::IWireCodec {
public:
    void RegisterType(eprosima::fastdds::dds::DomainParticipant* participant) override {
        type_ = eprosima::fastdds::dds::TypeSupport(new BrakeCmdPubSubType());
        type_.register_type(participant);
        type_name_ = type_.get_type_name();
    }
    const char* type_name() const override { return type_name_.c_str(); }

    void Publish(eprosima::fastdds::dds::DataWriter* writer, const sils::BehaviorOutput& out,
                 uint64_t tick_seq, sils::WireFault fault) override {
        BrakeCmd sample;
        sample.seq(tick_seq);
        // Corrupt on a TYPED wire = an out-of-contract value (NaN force), not garbage
        // bytes -- distinct from the VISS codec's malformed-string corruption, and what
        // analyze_plant fail-fasts on (§14). Drop is handled by RunProbe (no Publish).
        sample.force(fault == sils::WireFault::Corrupt ? std::nan("") : out.value);
        writer->write(&sample);
        if (fault == sils::WireFault::Duplicate) writer->write(&sample);
    }

    // Read path (symmetry of Publish): take BrakeCmd samples and correlate each by the
    // seq it carries. This ECU publishes one-way, so Take is exercised only if the run
    // enables reqresp/input-staging on a BrakeCmd topic -- but implementing it keeps the
    // codec a full IWireCodec, and (crucially) means run_loop's read path never names a
    // concrete type, so this ECU compiles NO VISS-generated sources.
    std::vector<sils::WireInbound> Take(eprosima::fastdds::dds::DataReader* reader) override {
        std::vector<sils::WireInbound> out;
        BrakeCmd sample;
        eprosima::fastdds::dds::SampleInfo info;
        while (reader->take_next_sample(&sample, &info) == eprosima::fastdds::dds::RETCODE_OK) {
            if (!info.valid_data) continue;
            out.push_back(sils::WireInbound{sils::RequestId(sample.seq()), "", ""});
        }
        return out;
    }

    const char* name() const override { return "brake-cmd-native"; }

private:
    eprosima::fastdds::dds::TypeSupport type_;
    std::string type_name_;
};

#endif  // BRAKE_ECU_NATIVE_WIRE_HPP
